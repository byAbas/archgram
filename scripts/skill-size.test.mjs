// The archgram skill's sizing script, packages/archgram/skill/size.mjs
// (`archgram-size` in the npm package),
// with Node's own test runner: `node --test scripts/skill-size.test.mjs`.
// Each test builds a small project in a temporary folder, a git repository
// unless it says otherwise, and reads what the script prints.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const script = path.join(path.dirname(fileURLToPath(import.meta.url)), '../packages/archgram/skill/size.mjs');

function project(files, { git = true } = {}) {
  const dir = mkdtempSync(path.join(tmpdir(), 'archgram-size-'));
  for (const [name, text] of Object.entries(files)) {
    const full = path.join(dir, name);
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, text);
  }
  if (git) {
    execFileSync('git', ['init', '-q'], { cwd: dir });
    execFileSync('git', ['add', '-A', '-f', '--', ...Object.keys(files).filter((f) => !f.startsWith('ignored/'))], { cwd: dir });
  }
  return dir;
}

function size(dir, ...args) {
  const run = spawnSync(process.execPath, [script, ...args], { cwd: dir, encoding: 'utf8' });
  return { code: run.status, out: run.stdout, err: run.stderr };
}

const row = (out, start) => out.split('\n').find((l) => l.startsWith(`| ${start} |`));
const section = (out, name) => out.split(`## ${name}\n`)[1]?.split('\n## ')[0] ?? '';

test('it reads the project and leaves out what is never its own', (t) => {
  const dir = project({
    'src/api.js': 'const db = require("./db");\napp.post("/orders", save);\n',
    'src/db.js': 'module.exports = {};\n',
    'vendor/lib/x.js': 'x();\n',
    'web/node_modules/left/index.js': 'y();\n',
    'package-lock.json': '{}\n',
    'public/app.min.js': 'a();\n',
    'gen/zz_generated.deepcopy.go': 'package gen\n',
    'gen/api.go': '// Code generated by protoc. DO NOT EDIT.\npackage gen\n',
    'docs/logo.svg': '<svg/>\n',
    'build/make.sh': 'cargo build\n',
  });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const { code, out } = size(dir);
  assert.equal(code, 0);
  assert.match(out, /^Read: 3 files, 4 lines, /m, 'src/api.js, src/db.js and build/make.sh');
  const left = section(out, 'Left out');
  assert.match(left, /\| vendor\/ \| 1 \| never the project's own/);
  assert.match(left, /\| web\/node_modules\/ \| 1 \| never the project's own/);
  assert.match(left, /\| \.\/ \| 1 \| a lock file/);
  assert.match(left, /\| public\/ \| 1 \| minified/);
  assert.match(left, /\| gen\/ \| 1 \| generated, by its name/);
  assert.match(left, /\| gen\/ \| 1 \| generated, by its first lines/);
  assert.match(left, /\| docs\/ \| 1 \| an image, a font or other media/);
  assert.ok(!left.includes('build/'), 'build/ holds source here, so it is read');
});

test('it follows the project\'s marks in .gitattributes, both ways', (t) => {
  const dir = project({
    '.gitattributes': 'src/schema.js linguist-generated\nvendor/ours/** -linguist-vendored\n',
    'src/schema.js': 'export const s = 1;\n',
    'src/app.js': 'run();\n',
    'vendor/ours/kept.js': 'mine();\n',
  });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const { out } = size(dir);
  const left = section(out, 'Left out');
  assert.match(left, /\| src\/ \| 1 \| marked in \.gitattributes/);
  assert.ok(!left.includes('vendor/'), 'un-vendored with -linguist-vendored, so read');
  assert.match(out, /^Read: 3 files, /m, '.gitattributes, src/app.js and vendor/ours/kept.js');
});

test('what git ignores and does not track is listed, not read', (t) => {
  const dir = project({
    '.gitignore': 'ignored/\n',
    'src/app.js': 'run();\n',
    'ignored/big.js': 'z();\n',
  });
  writeFileSync(path.join(dir, 'new.js'), 'n();\n');
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const left = section(size(dir).out, 'Left out');
  assert.match(left, /\| ignored\/ \|  \| git ignores it/);
  assert.match(left, /\| new\.js \|  \| git does not track it/);
});

test('a symbolic link is not followed', (t) => {
  const outside = mkdtempSync(path.join(tmpdir(), 'archgram-outside-'));
  writeFileSync(path.join(outside, 'secret.js'), 'secret();\n');
  const dir = project({ 'src/app.js': 'run();\n' });
  symlinkSync(path.join(outside, 'secret.js'), path.join(dir, 'src', 'link.js'));
  execFileSync('git', ['add', '-A'], { cwd: dir });
  t.after(() => {
    rmSync(dir, { recursive: true, force: true });
    rmSync(outside, { recursive: true, force: true });
  });
  const { out } = size(dir);
  assert.match(section(out, 'Left out'), /\| src\/ \| 1 \| a symbolic link, not followed/);
  assert.match(out, /^Read: 1 files, /m);
});

test('an area over the budget splits into its folders', (t) => {
  const line = `${'x'.repeat(399)}\n`; // 400 bytes, about 100 tokens
  const files = {};
  for (let i = 0; i < 15; i++) files[`src/a/f${i}.js`] = line;
  for (let i = 0; i < 15; i++) files[`src/b/f${i}.js`] = line;
  files['src/index.js'] = line;
  const dir = project(files);
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const whole = size(dir, '--budget', '5000');
  assert.match(whole.out, /^Size: small, 1 area$/m);
  const split = size(dir, '--budget', '1000');
  assert.match(split.out, /^Size: medium, 3 areas$/m);
  assert.ok(row(split.out, 'src/a/'));
  assert.ok(row(split.out, 'src/b/'));
  assert.ok(row(split.out, 'src/ (its own files)'));
});

test('paths narrow it to the scope, and one outside the project is refused', (t) => {
  const dir = project({ 'src/api.js': 'a();\n', 'web/app.js': 'b();\n' });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const scoped = size(dir, 'src');
  assert.match(scoped.out, /^Scope: src$/m);
  assert.match(scoped.out, /^Read: 1 files, /m);
  const outside = size(dir, '..');
  assert.equal(outside.code, 2);
  assert.match(outside.err, /outside the project/);
  assert.equal(size(dir, 'nowhere').code, 2);
  assert.equal(size(dir, '--budget', '5').code, 2);
});

test('the same project prints the same, run after run', (t) => {
  const dir = project({ 'b.js': 'b();\n', 'a/x.js': 'x();\n', 'a/y.js': 'y();\n', 'vendor/v.js': 'v();\n' });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  assert.equal(size(dir).out, size(dir).out);
});

test('outside git it walks the folder, and does not walk into one never its own', (t) => {
  const dir = project({ 'src/app.js': 'run();\n', 'node_modules/dep/index.js': 'dep();\n' }, { git: false });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const { code, out } = size(dir);
  assert.equal(code, 0);
  assert.match(out, /^Not a git repository/m);
  assert.match(out, /^Read: 1 files, /m);
  assert.match(section(out, 'Left out'), /\| node_modules\/ \|  \| never the project's own/);
});

test('a file that commonly holds secrets is left out by its name, never opened', (t) => {
  // The list docs/SPEC.md (Sources) gives, so a name added there is held
  // here too: a pattern becomes a file of that pattern, a folder a file in it.
  const spec = readFileSync(path.join(path.dirname(script), '../../../docs/SPEC.md'), 'utf8');
  const sentence = spec.split('commonly holds secrets rather than code (')[1].split(').')[0];
  const names = [...sentence.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
  assert.ok(names.includes('.env') && names.includes('.ssh'), sentence);
  const folders = new Set(['.ssh', '.aws', '.gnupg', '.docker']);
  const files = names.map((n) => (folders.has(n) ? `${n}/config` : n.replace('*', 'x')));

  const dir = project({ 'src/app.js': 'run();\n', ...Object.fromEntries(files.map((f) => [f, 'TOKEN=secret\n'])) });
  // Unreadable once git has them: a script that opened one would fail to,
  // and drop it, instead of listing it as left out.
  for (const f of files) chmodSync(path.join(dir, f), 0o000);
  t.after(() => {
    for (const f of files) chmodSync(path.join(dir, f), 0o600);
    rmSync(dir, { recursive: true, force: true });
  });

  const { code, out } = size(dir);
  assert.equal(code, 0);
  assert.match(out, /^Read: 1 files, /m, 'only src/app.js');
  const left = section(out, 'Left out');
  const secret = left
    .split('\n')
    .filter((l) => l.includes('commonly holds secrets: never opened'))
    .reduce((n, l) => n + Number(l.split('|')[2].trim()), 0);
  assert.equal(secret, files.length, `${files.length} secret files, each left out:\n${left}`);
  assert.ok(!out.includes('TOKEN'), 'nothing of a secret is printed');
});

test('a project in a folder its enclosing repository ignores is walked, not refused', (t) => {
  const outer = project({ '.gitignore': 'inner/\n', 'top.js': 't();\n' });
  const inner = path.join(outer, 'inner');
  mkdirSync(path.join(inner, 'src'), { recursive: true });
  writeFileSync(path.join(inner, 'src/app.js'), 'run();\n');
  t.after(() => rmSync(outer, { recursive: true, force: true }));
  const { code, out, err } = size(inner);
  assert.equal(code, 0, err);
  assert.match(out, /^In a folder its git repository ignores/m);
  assert.match(out, /^Read: 1 files, /m, 'src/app.js, and nothing of the enclosing repository');
});
